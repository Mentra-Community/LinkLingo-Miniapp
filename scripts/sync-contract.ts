/**
 * Copies the Mandarin learning transport contract into this repo.
 *
 *   bun scripts/sync-contract.ts          write the copies
 *   bun scripts/sync-contract.ts --check  fail if a copy is stale (local gate: `bun run contract:check`)
 *
 * Source of truth: mandarin-app/contract/src/learning/v1.ts. Never edit the
 * copies; change the source and re-sync. The miniapp background copy is used
 * with `import type` only, so zod is not bundled into the phone.
 */
import {existsSync, mkdirSync, readFileSync, writeFileSync} from "node:fs"
import {dirname, resolve} from "node:path"
import {format, resolveConfig} from "prettier"

const root = resolve(import.meta.dir, "..")
const source = resolve(process.env.MANDARIN_APP_DIR ?? resolve(root, "../mandarin-app"), "contract/src/learning/v1.ts")
const targets = [
  {path: resolve(root, "backend/src/vendor/mandarin-contract.ts"), prettier: false},
  {path: resolve(root, "miniapp/src/shared/mandarin-contract.ts"), prettier: true},
]
const HEADER = "// GENERATED by scripts/sync-contract.ts from mandarin-app/contract/src/learning/v1.ts. Do not edit.\n"

if (!existsSync(source)) {
  console.error(`contract source not found: ${source} (set MANDARIN_APP_DIR)`)
  process.exit(2)
}

const body = HEADER + readFileSync(source, "utf8")
const check = process.argv.includes("--check")
let stale = 0
for (const target of targets) {
  const expected = target.prettier
    ? await format(body, {...(await resolveConfig(target.path)), filepath: target.path})
    : body
  const current = existsSync(target.path) ? readFileSync(target.path, "utf8") : null
  if (current === expected) continue
  if (check) {
    console.error(`stale: ${target.path}`)
    stale++
    continue
  }
  mkdirSync(dirname(target.path), {recursive: true})
  writeFileSync(target.path, expected)
  console.log(`wrote ${target.path}`)
}
if (check && stale > 0) {
  console.error("run `bun run contract:sync` and commit the result")
  process.exit(1)
}
if (check) console.log("contract copies are current")
